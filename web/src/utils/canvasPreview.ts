export function buildInitialSceneCodes(
  mockCodes: Record<string, SceneCode>
): Record<string, SceneCode> {
  return {
    ...mockCodes,
    "scene-6-ending": mockCodes["scene-6-ending"] ?? {
      sceneId: "scene-6-ending",
      attempts: 1,
      source: "argon-code",
      code: DEFAULT_ENDING_CODE,
    },
  };
}

/**
 * Safely executes `draw(ctx, t, w, h, scene)` generated by Argon.
 * Falls back to a deterministic template if compilation/execution throws.
 */
export function renderMotionSceneToCanvas(
  ctx: CanvasRenderingContext2D,
  t: number,
  w: number,
  h: number,
  scene: PlannedScene,
  sceneCode?: SceneCode
): { ok: boolean; error?: string } {
  ctx.save();
  try {
    const codeStr = sceneCode?.code || DEFAULT_ENDING_CODE;
    const fn = new Function("ctx", "t", "w", "h", "scene", codeStr);
    fn(ctx, t, w, h, scene);
    ctx.restore();
    return { ok: true };
  } catch (err) {
    ctx.restore();
    renderFallbackTemplate(ctx, t, w, h, scene);
    return {
      ok: false,
      error: err instanceof Error ? err.message : String(err),
    };
  }
}

export function renderFallbackTemplate(
  ctx: CanvasRenderingContext2D,
  t: number,
  w: number,
  h: number,
  scene: PlannedScene
) {
  const dur = scene.durationSec || 4;
  const p = Math.min(1, Math.max(0, t / dur));
  ctx.save();
  ctx.fillStyle = scene.kind === "ending" ? "#111111" : "#F8F9FA";
  ctx.fillRect(0, 0, w, h);

  ctx.fillStyle = "#C6FF00";
  ctx.fillRect(w * 0.08, h * 0.14, 280, 52);
  ctx.fillStyle = "#111111";
  ctx.font = "900 26px sans-serif";
  ctx.textBaseline = "middle";
  ctx.fillText(
    scene.kind === "ending" ? "ENDING CARD" : "TEMPLATE FALLBACK",
    w * 0.08 + 22,
    h * 0.14 + 26
  );

  ctx.fillStyle = scene.kind === "ending" ? "#FFFFFF" : "#111111";
  ctx.font = "900 62px sans-serif";
  ctx.fillText(scene.caption, w * 0.08, h * 0.34);

  ctx.fillStyle = scene.kind === "ending" ? "#C6FF00" : "#344054";
  ctx.font = "700 42px sans-serif";
  ctx.fillText(scene.script, w * 0.08, h * 0.48);

  if (scene.visuals && scene.visuals.length > 0) {
    scene.visuals.forEach((v, idx) => {
      const appear = Math.min(1, Math.max(0, (p - idx * 0.18) * 3));
      ctx.globalAlpha = appear;
      ctx.fillStyle = "#111111";
      ctx.fillRect(w * 0.08, h * 0.6 + idx * 90, w * 0.84, 72);
      ctx.fillStyle = "#C6FF00";
      ctx.font = "800 34px sans-serif";
      ctx.fillText(`✓ ${v}`, w * 0.1, h * 0.6 + idx * 90 + 36);
    });
  }
  ctx.restore();
}

/**
 * Renders an `original` camera scene onto the 1920x1080 canvas.
 * If a real HTMLVideoElement is loaded and ready, draws the video frame;
 * otherwise draws a studio-grade simulated creator camera feed so the demo works out of the box.
 */
export function renderOriginalSceneToCanvas(
  ctx: CanvasRenderingContext2D,
  t: number,
  w: number,
  h: number,
  scene: PlannedScene,
  videoEl?: HTMLVideoElement | null,
  profileImg?: HTMLImageElement | null
) {
  ctx.save();

  const hasLiveVideo =
    videoEl && videoEl.readyState >= 2 && videoEl.videoWidth > 0;

  if (hasLiveVideo) {
    // Draw video cover-fit into 1920x1080
    const vw = videoEl.videoWidth;
    const vh = videoEl.videoHeight;
    const scale = Math.max(w / vw, h / vh);
    const dw = vw * scale;
    const dh = vh * scale;
    ctx.drawImage(videoEl, (w - dw) / 2, (h - dh) / 2, dw, dh);
  } else {
    // Simulated creator camera shot for instant 0-setup demo
    const grad = ctx.createLinearGradient(0, 0, w, h);
    grad.addColorStop(0, "#181c24");
    grad.addColorStop(0.5, "#232a38");
    grad.addColorStop(1, "#12151c");
    ctx.fillStyle = grad;
    ctx.fillRect(0, 0, w, h);

    // Subtle studio lighting glow
    const radial = ctx.createRadialGradient(
      w * 0.5,
      h * 0.42,
      60,
      w * 0.5,
      h * 0.42,
      w * 0.45
    );
    radial.addColorStop(0, "rgba(62, 166, 255, 0.18)");
    radial.addColorStop(1, "rgba(0, 0, 0, 0)");
    ctx.fillStyle = radial;
    ctx.fillRect(0, 0, w, h);

    // Camera viewfinder brackets
    ctx.strokeStyle = "rgba(255,255,255,0.22)";
    ctx.lineWidth = 4;
    const m = 64;
    const bl = 48;
    // Top-left
    ctx.beginPath();
    ctx.moveTo(m, m + bl);
    ctx.lineTo(m, m);
    ctx.lineTo(m + bl, m);
    ctx.stroke();
    // Top-right
    ctx.beginPath();
    ctx.moveTo(w - m - bl, m);
    ctx.lineTo(w - m, m);
    ctx.lineTo(w - m, m + bl);
    ctx.stroke();
    // Bottom-left
    ctx.beginPath();
    ctx.moveTo(m, h - m - bl);
    ctx.lineTo(m, h - m);
    ctx.lineTo(m + bl, h - m);
    ctx.stroke();
    // Bottom-right
    ctx.beginPath();
    ctx.moveTo(w - m - bl, h - m);
    ctx.lineTo(w - m, h - m);
    ctx.lineTo(w - m, h - m - bl);
    ctx.stroke();

    // Top-left REC & Source Range indicator
    const srcStart = scene.sourceRange?.start ?? 0;
    const srcTime = (srcStart + t).toFixed(1);
    ctx.fillStyle = "rgba(17, 17, 17, 0.78)";
    ctx.fillRect(m + 20, m + 20, 460, 58);
    ctx.fillStyle = "#FF3B30";
    ctx.beginPath();
    ctx.arc(m + 52, m + 49, 10, 0, Math.PI * 2);
    ctx.fill();
    ctx.fillStyle = "#FFFFFF";
    ctx.font = "700 26px sans-serif";
    ctx.textBaseline = "middle";
    ctx.fillText(
      `ORIGINAL KEEP · ${srcTime}s (${srcStart.toFixed(1)}s~${(scene.sourceRange?.end ?? srcStart + scene.durationSec).toFixed(1)}s)`,
      m + 76,
      m + 49
    );

    // Center creator avatar + dynamic voice ring
    const cx = w * 0.5;
    const cy = h * 0.4;
    const pulse = 1 + Math.sin(t * 14) * 0.06;

    ctx.strokeStyle = "#C6FF00";
    ctx.lineWidth = 6;
    ctx.beginPath();
    ctx.arc(cx, cy, 118 * pulse, 0, Math.PI * 2);
    ctx.stroke();

    if (profileImg && profileImg.complete && profileImg.naturalWidth > 0) {
      ctx.save();
      ctx.beginPath();
      ctx.arc(cx, cy, 104, 0, Math.PI * 2);
      ctx.clip();
      ctx.drawImage(profileImg, cx - 104, cy - 104, 208, 208);
      ctx.restore();
    } else {
      ctx.fillStyle = "#282828";
      ctx.beginPath();
      ctx.arc(cx, cy, 104, 0, Math.PI * 2);
      ctx.fill();
      ctx.fillStyle = "#C6FF00";
      ctx.font = "900 44px sans-serif";
      ctx.textAlign = "center";
      ctx.fillText("AI쭌", cx, cy);
      ctx.textAlign = "start";
    }

    // Simulated live audio waveform bars below avatar
    const barCount = 24;
    const barW = 12;
    const barGap = 8;
    const totalBarW = barCount * (barW + barGap);
    const startBx = cx - totalBarW / 2;
    for (let i = 0; i < barCount; i++) {
      const wave =
        Math.abs(Math.sin(t * 10 + i * 0.55) * Math.cos(t * 6 - i * 0.3)) * 54 +
        10;
      ctx.fillStyle = i % 3 === 0 ? "#C6FF00" : "#3EA6FF";
      ctx.fillRect(
        startBx + i * (barW + barGap),
        cy + 150 - wave / 2,
        barW,
        wave
      );
    }
  }

  // Lower-third broadcast caption bar (AI쭌 signature style: Ink #111111 + Lime #C6FF00)
  const barY = h - 220;
  ctx.fillStyle = "rgba(17, 17, 17, 0.92)";
  ctx.fillRect(w * 0.08, barY, w * 0.84, 148);
  ctx.fillStyle = "#C6FF00";
  ctx.fillRect(w * 0.08, barY, 16, 148);

  // Caption tag
  ctx.fillStyle = "#C6FF00";
  ctx.font = "800 28px sans-serif";
  ctx.textBaseline = "middle";
  ctx.fillText(scene.caption, w * 0.08 + 42, barY + 46);

  // Spoken script subtitle
  ctx.fillStyle = "#FFFFFF";
  ctx.font = "700 40px sans-serif";
  ctx.fillText(`"${scene.script}"`, w * 0.08 + 42, barY + 104);

  ctx.restore();
}

/**
 * Generates a 320x180 keyframe thumbnail data URL for the scene strip.
 */
export function renderSceneThumbnailDataUrl(
  scene: PlannedScene,
  sceneCode?: SceneCode
): string {
  const canvas = document.createElement("canvas");
  canvas.width = 1920;
  canvas.height = 1080;
  const ctx = canvas.getContext("2d");
  if (!ctx) return "";

  const sampleT = Math.max(0.5, (scene.durationSec || 3) * 0.65);
  if (scene.kind === "original") {
    renderOriginalSceneToCanvas(ctx, sampleT, 1920, 1080, scene, null, null);
  } else {
    renderMotionSceneToCanvas(ctx, sampleT, 1920, 1080, scene, sceneCode);
  }

  // Downscale to 320x180 for crisp fast thumbnails
  const thumb = document.createElement("canvas");
  thumb.width = 320;
  thumb.height = 180;
  const tctx = thumb.getContext("2d");
  if (tctx) {
    tctx.drawImage(canvas, 0, 0, 320, 180);
  }
  return thumb.toDataURL("image/jpeg", 0.82);
}
