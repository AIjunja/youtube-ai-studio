export const DEFAULT_ENDING_CODE = FALLBACK_TEMPLATES.ending;

export function buildInitialSceneCodes(
  mockCodes: Record<string, SceneCode>
): Record<string, SceneCode> {
  return {
    ...mockCodes,
    "scene-6-ending": mockCodes["scene-6-ending"] ?? {
      sceneId: "scene-6-ending",
      attempts: 1,
      source: "argon-code",
      code: DEFAULT_ENDING_CODE,
    },
  };
}

/**
 * Safely executes `draw(ctx, t, w, h, scene, kit)` generated by Argon.
 * Falls back to a deterministic v2 motion template if compilation/execution throws.
 */
export function renderMotionSceneToCanvas(
  ctx: CanvasRenderingContext2D,
  t: number,
  w: number,
  h: number,
  scene: PlannedScene,
  sceneCode?: SceneCode
): { ok: boolean; error?: string } {
  ctx.save();
  try {
    const codeStr = sceneCode?.code || DEFAULT_ENDING_CODE;
    const kit = createMotionKit(ctx, t, w, h, scene);
    const fn = new Function("ctx", "t", "w", "h", "scene", "kit", codeStr);
    fn(ctx, t, w, h, scene, kit);
    ctx.restore();
    return { ok: true };
  } catch (err) {
    ctx.restore();
    renderFallbackTemplate(ctx, t, w, h, scene);
    return {
      ok: false,
      error: err instanceof Error ? err.message : String(err),
    };
  }
}

export function renderFallbackTemplate(
  ctx: CanvasRenderingContext2D,
  t: number,
  w: number,
  h: number,
  scene: PlannedScene
): void {
  drawTemplateFallback(ctx, t, w, h, scene);
}

/**
 * Renders an `original` camera scene onto the 1920x1080 canvas.
 * If a real HTMLVideoElement is loaded and ready, draws the video frame;
 * otherwise draws a clean studio camera simulation without internal debug strings.
 */
export function renderOriginalSceneToCanvas(
  ctx: CanvasRenderingContext2D,
  t: number,
  w: number,
  h: number,
  scene: PlannedScene,
  videoEl?: HTMLVideoElement | null,
  profileImg?: HTMLImageElement | null
): void {
  ctx.save();
  const s = w / 1920;

  const hasLiveVideo =
    videoEl && videoEl.readyState >= 2 && videoEl.videoWidth > 0;

  if (hasLiveVideo) {
    const vw = videoEl.videoWidth;
    const vh = videoEl.videoHeight;
    const scale = Math.max(w / vw, h / vh);
    const dw = vw * scale;
    const dh = vh * scale;
    ctx.drawImage(videoEl, (w - dw) / 2, (h - dh) / 2, dw, dh);
  } else {
    const grad = ctx.createLinearGradient(0, 0, w, h);
    grad.addColorStop(0, "#181C24");
    grad.addColorStop(0.5, "#232A38");
    grad.addColorStop(1, "#12151C");
    ctx.fillStyle = grad;
    ctx.fillRect(0, 0, w, h);

    const radial = ctx.createRadialGradient(
      w * 0.5,
      h * 0.42,
      60 * s,
      w * 0.5,
      h * 0.42,
      w * 0.45
    );
    radial.addColorStop(0, "rgba(215, 255, 58, 0.14)");
    radial.addColorStop(1, "rgba(0, 0, 0, 0)");
    ctx.fillStyle = radial;
    ctx.fillRect(0, 0, w, h);

    // Subtle viewfinder corners within safe margins
    ctx.strokeStyle = "rgba(250, 250, 248, 0.22)";
    ctx.lineWidth = Math.max(2, 4 * s);
    const mx = 120 * s;
    const my = 96 * s;
    const bl = 44 * s;
    ctx.beginPath();
    ctx.moveTo(mx, my + bl);
    ctx.lineTo(mx, my);
    ctx.lineTo(mx + bl, my);
    ctx.stroke();

    ctx.beginPath();
    ctx.moveTo(w - mx - bl, my);
    ctx.lineTo(w - mx, my);
    ctx.lineTo(w - mx, my + bl);
    ctx.stroke();

    // Center creator avatar + dynamic voice ring
    const cx = w * 0.5;
    const cy = h * 0.4;
    const pulse = 1 + Math.sin(t * 14) * 0.05;

    ctx.strokeStyle = MOTION_DESIGN.colors.lime;
    ctx.lineWidth = Math.max(3, 6 * s);
    ctx.beginPath();
    ctx.arc(cx, cy, 118 * s * pulse, 0, Math.PI * 2);
    ctx.stroke();

    if (profileImg && profileImg.complete && profileImg.naturalWidth > 0) {
      ctx.save();
      ctx.beginPath();
      ctx.arc(cx, cy, 104 * s, 0, Math.PI * 2);
      ctx.clip();
      ctx.drawImage(
        profileImg,
        cx - 104 * s,
        cy - 104 * s,
        208 * s,
        208 * s
      );
      ctx.restore();
    } else {
      ctx.fillStyle = "#282828";
      ctx.beginPath();
      ctx.arc(cx, cy, 104 * s, 0, Math.PI * 2);
      ctx.fill();
      ctx.fillStyle = MOTION_DESIGN.colors.lime;
      ctx.font = `700 ${Math.round(44 * s)}px ${MOTION_DESIGN.fonts.bold}`;
      ctx.textAlign = "center";
      ctx.textBaseline = "middle";
      ctx.fillText("AI쭌", cx, cy);
      ctx.textAlign = "left";
    }

    // Live audio waveform bars below avatar
    const barCount = 24;
    const barW = 12 * s;
    const barGap = 8 * s;
    const totalBarW = barCount * (barW + barGap);
    const startBx = cx - totalBarW / 2;
    for (let i = 0; i < barCount; i++) {
      const wave =
        (Math.abs(Math.sin(t * 10 + i * 0.55) * Math.cos(t * 6 - i * 0.3)) *
          54 +
          10) *
        s;
      ctx.fillStyle = i % 3 === 0 ? MOTION_DESIGN.colors.lime : "#FAFAF8";
      ctx.fillRect(
        startBx + i * (barW + barGap),
        cy + 155 * s - wave / 2,
        barW,
        wave
      );
    }
  }

  // Broadcast lower-third caption bar (Ink #0E0E10 + Lime #D7FF3A)
  const barW = w - 240 * s;
  const barH = 148 * s;
  const barX = 120 * s;
  const barY = h - 96 * s - barH;

  ctx.fillStyle = "rgba(14, 14, 16, 0.94)";
  ctx.fillRect(barX, barY, barW, barH);
  ctx.fillStyle = MOTION_DESIGN.colors.lime;
  ctx.fillRect(barX, barY, 16 * s, barH);

  drawWrappedText(ctx, scene.caption || "", barX + 44 * s, barY + 24 * s, {
    maxWidth: barW - 80 * s,
    fontSize: Math.round(34 * s),
    minFontSize: Math.round(34 * s),
    fontFamily: MOTION_DESIGN.fonts.bold,
    fontWeight: 700,
    color: MOTION_DESIGN.colors.lime,
    maxLines: 1,
  });

  drawWrappedText(ctx, scene.script || "", barX + 44 * s, barY + 76 * s, {
    maxWidth: barW - 80 * s,
    fontSize: Math.round(42 * s),
    minFontSize: Math.round(34 * s),
    fontFamily: MOTION_DESIGN.fonts.medium,
    fontWeight: 500,
    color: MOTION_DESIGN.colors.bgLight,
    maxLines: 1,
  });

  ctx.restore();
}

/**
 * Generates a 320x180 keyframe thumbnail data URL for the scene strip.
 */
export function renderSceneThumbnailDataUrl(
  scene: PlannedScene,
  sceneCode?: SceneCode
): string {
  const canvas = document.createElement("canvas");
  canvas.width = 1920;
  canvas.height = 1080;
  const ctx = canvas.getContext("2d");
  if (!ctx) return "";

  const sampleT = Math.max(0.5, (scene.durationSec || 3) * 0.65);
  if (scene.kind === "original") {
    renderOriginalSceneToCanvas(ctx, sampleT, 1920, 1080, scene, null, null);
  } else {
    renderMotionSceneToCanvas(ctx, sampleT, 1920, 1080, scene, sceneCode);
  }

  const thumb = document.createElement("canvas");
  thumb.width = 320;
  thumb.height = 180;
  const tctx = thumb.getContext("2d");
  if (tctx) {
    tctx.drawImage(canvas, 0, 0, 320, 180);
  }
  return thumb.toDataURL("image/jpeg", 0.85);
}
